import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

const DROP_REAL = new Set([
  'real-05', 'real-07', 'real-08', 'real-12', 'real-13', 'real-20', 'real-23', 'real-24', 'real-25', 'real-26',
  'real-29', 'real-33', 'real-34', 'real-37', 'real-39', 'real-52', 'real-53', 'real-56', 'real-57', 'real-60',
]);
const W = 720, H = 540;

const real = JSON.parse(readFileSync('raw/real/candidates.json', 'utf8')).filter((r) => !DROP_REAL.has(r.id));
const perfect = JSON.parse(readFileSync('raw/perfect/candidates.json', 'utf8'));
const ai = JSON.parse(readFileSync('raw/ai/candidates.json', 'utf8'));
const hard = JSON.parse(readFileSync('raw/hard/candidates.json', 'utf8'));
const DIRS = { real: 'raw/real', perfect: 'raw/perfect', ai: 'raw/ai', hard: 'raw/hard' };

rmSync('public/img', { recursive: true, force: true });
mkdirSync('public/img', { recursive: true });

const credits = [];
for (const item of [...real, ...perfect, ...ai, ...hard]) {
  const dir = DIRS[item.id.split('-')[0]];
  const jpeg = await sharp(`${dir}/${item.id}.jpg`)
    .rotate()
    .resize(W, H, { fit: 'cover', position: 'attention' })
    .jpeg({ quality: 72, mozjpeg: true }) // sharp drops EXIF/XMP/ICC/C2PA unless asked to keep them
    .toBuffer();
  const name = createHash('sha256').update(jpeg).digest('hex').slice(0, 16) + '.jpg';
  writeFileSync(`public/img/${name}`, jpeg);
  const { id, ...rest } = item;
  credits.push({
    file: `img/${name}`,
    ...rest,
    license: rest.license.replace(' (CC0)', ''),
    author: rest.author.replace(/^Creator:/, ''),
  });
}
credits.sort((a, b) => a.file.localeCompare(b.file));

const deck = credits.map(({ file, answer, author, license, source }) =>
  answer === 'real' ? { f: file, a: answer, by: author, lic: license, src: source } : { f: file, a: answer });
credits.forEach((c, i) => { if (c.hard) deck[i].h = 1; });

writeFileSync('credits.json', JSON.stringify(credits, null, 2) + '\n');
writeFileSync(
  'src/deck.js',
  `// Generated by scripts/build-images.mjs. Bundled into the Worker only; never served as a static asset.\nexport const DECK = ${JSON.stringify(deck, null, 1)};\n`,
);
console.log(`real=${real.length} too_perfect=${perfect.length} ai=${ai.length} hard=${hard.length} total=${credits.length}`);
